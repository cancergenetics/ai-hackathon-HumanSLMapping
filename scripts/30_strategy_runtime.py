#!/usr/bin/env python
"""Selection runtime per round for every strategy (DESIGN v3.1 §6.2 compute rule) on dev split 1 at
n ∈ {0, 30, 160, 330, 660} (random screened sets drawn with strategy_runtime_draw_seed; runtime only — no labels are
scored). ≤ 2 BLAS/OpenMP threads. For each (strategy, n): `first` = first call of a fresh selector with the in-memory
kernel caches cleared (includes the one-off, screened-set-independent cache builds: external kernel / kernel PCA /
R1 k-means / gene features), `round` = the next call on the same selector with warm caches (= the per-round cost
inside a trajectory). Output: results/strategies/selection_runtime.{md,json}.

    .venv/bin/python scripts/30_strategy_runtime.py
"""
from __future__ import annotations

import os

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "VECLIB_MAXIMUM_THREADS"):
    os.environ.setdefault(_v, "2")

import hsl  # noqa: E402,F401  (guard + label gate)

import json  # noqa: E402
import platform  # noqa: E402
import time  # noqa: E402

import numpy as np  # noqa: E402

from hsl import config, harness, paths, strategies, views  # noqa: E402
from hsl.strategies import kernels  # noqa: E402

NS = (0, 30, 160, 330, 660)
NAMES = strategies.ARMS + ("C-static",)


def main():
    b = views.dev_bundle()
    sp = views.dev_split(1)
    rng = np.random.default_rng(config.seed("strategy_runtime_draw_seed"))
    perm = sp.pool[rng.permutation(len(sp.pool))]
    rows = []
    for n in NS:
        S = np.sort(perm[:n])
        t = time.perf_counter()
        v = views.SelectorView.build(b, S, sp)
        t_view = time.perf_counter() - t
        for name in NAMES:
            kernels.clear_cache()
            sel = strategies.make(name)
            r = np.random.default_rng(0)
            sel.reset(v.candidates, r)
            t = time.perf_counter()
            sel.select(v, 10, r)
            t_first = time.perf_counter() - t
            t = time.perf_counter()
            sel.select(views.SelectorView.build(b, S, sp), 10, r)   # same S (selection is not committed)
            t_round = time.perf_counter() - t
            phase = (sel.diagnostics[-1] or {}).get("phase")
            rows.append({"strategy": name, "n": n, "first_s": t_first, "round_s": t_round, "view_s": t_view,
                         "phase": phase, "n_candidates": int(len(v.candidates))})
            print(f"{name:9s} n={n:4d} first {t_first:6.2f}s round {t_round:6.2f}s ({phase})", flush=True)
    out = {"split": "dev1", "threads": os.environ["OMP_NUM_THREADS"], "machine": platform.platform(),
           "git": harness._git(), "rows": rows}
    d = paths.output_root() / "results" / "strategies"
    d.mkdir(parents=True, exist_ok=True)
    (d / "selection_runtime.json").write_text(json.dumps(out, indent=1) + "\n")
    lines = ["# Strategy selection runtime per round (dev split 1)", "",
             "Seconds per `select(view, 10, rng)` call, ≤ 2 BLAS/OpenMP threads, random screened sets "
             "(strategy_runtime_draw_seed). `round` = per-round cost inside a trajectory (warm in-memory caches); "
             "`first` = first call of a trajectory incl. the one-off screened-set-independent cache builds (external "
             "kernel PSD projections, kernel PCA, R1 k-means, gene features). SelectorView build time (harness, not "
             "the selector) in the last row. Machine shared with a concurrent P1 job (timings are upper bounds). "
             "Generated by scripts/30_strategy_runtime.py.", "",
             "| strategy | " + " | ".join(f"n={n} round (first)" for n in NS) + " |",
             "|---|" + "---|" * len(NS)]
    for name in NAMES:
        cells = []
        for n in NS:
            r = next(x for x in rows if x["strategy"] == name and x["n"] == n)
            cells.append(f"{r['round_s']:.2f} ({r['first_s']:.1f})")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines.append("| SelectorView.build | " + " | ".join(
        f"{next(x for x in rows if x['n'] == n)['view_s']:.2f}" for n in NS) + " |")
    lines += ["", f"Phases: " + "; ".join(sorted({f"{x['strategy']}@{x['n']}={x['phase']}" for x in rows
                                                   if x['strategy'] in ('H', 'F', 'M')})), ""]
    (d / "selection_runtime.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
