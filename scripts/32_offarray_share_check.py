#!/usr/bin/env python
"""Off-array neutrality check (DESIGN §1, decision D5, strategy code review F-1/C-1/R1-1) on dev split 1: for every
selector and n ∈ {0, 30, 160, 330} (random screened start S_0 of size n, strategy_runtime_draw_seed), the off-array
share of the next 200 picks (R1: 220) made as in a trajectory — batches of 10, each round's picks revealed to the
next round's SelectorView (selection only: no predictor, nothing scored) — averaged over 3 selection seeds, vs the
off-array share of the S_0 candidates. Acceptance (PI): within ±5 percentage points (M exempt by spec after round 0:
off-array never picked). Secondary, descriptive: one-shot batch of 200 (cluster cap max(2, ⌈200/#clusters⌉) = 2:
spreads picks over clusters, which lowers the share where off-array genes concentrate in a cluster, e.g. dev1
cluster 5 = 34/40 off-array). ≤ 2 threads. Output: results/strategies/offarray_share.{md,json}.

    .venv/bin/python scripts/32_offarray_share_check.py
"""
from __future__ import annotations

import os

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "VECLIB_MAXIMUM_THREADS"):
    os.environ.setdefault(_v, "2")

import hsl  # noqa: E402,F401

import json  # noqa: E402

import numpy as np  # noqa: E402

from hsl import config, harness, paths, strategies, views  # noqa: E402

NS = (0, 30, 160, 330)
SEEDS = (0, 1, 2)
NAMES = strategies.ARMS + ("C-static",)
TOL = 0.05


def main():
    b = views.dev_bundle()
    sp = views.dev_split(1)
    rng = np.random.default_rng(config.seed("strategy_runtime_draw_seed"))
    perm = sp.pool[rng.permutation(len(sp.pool))]
    rows = []
    for n in NS:
        S = np.sort(perm[:n])
        v = views.SelectorView.build(b, S, sp)
        off = set(v.candidates[v.candidate_col < 0])
        base_share = len(off) / len(v.candidates)
        for name in NAMES:
            k = 220 if name == "R1" else 200
            sh, sh1 = [], []
            for s in SEEDS:
                sel = strategies.make(name)
                r = np.random.default_rng(s)
                sel.reset(v.candidates, r)
                picks: list = []
                while len(picks) < k:                      # trajectory regime, batches of 10
                    vv = views.SelectorView.build(b, np.concatenate([S, picks]), sp)
                    picks += sel.select(vv, min(10, k - len(picks)), r)
                sh.append(np.mean([g in off for g in picks]))
                sel = strategies.make(name)                # one-shot batch of 200 (descriptive)
                r = np.random.default_rng(s)
                sel.reset(v.candidates, r)
                sh1.append(np.mean([g in off for g in sel.select(v, 200, r)]))
            share, share1 = float(np.mean(sh)), float(np.mean(sh1))
            exempt = name == "M"                    # spec: off-array never picked after round 0
            ok = exempt or abs(share - base_share) <= TOL
            rows.append({"strategy": name, "n": n, "k": k, "share": share, "base": base_share, "ok": bool(ok),
                         "exempt": exempt, "per_seed": [float(x) for x in sh], "oneshot200": share1})
            print(f"{name:9s} n={n:4d} share {share:.3f} (one-shot {share1:.3f}) base {base_share:.3f} "
                  f"{'OK' if ok else 'FAIL'}", flush=True)
    d = paths.output_root() / "results" / "strategies"
    d.mkdir(parents=True, exist_ok=True)
    (d / "offarray_share.json").write_text(json.dumps({"split": "dev1", "git": harness._git(), "tol": TOL,
                                                       "rows": rows}, indent=1) + "\n")
    lines = ["# Off-array share of selections (dev split 1) — neutrality check", "",
             f"Off-array share of the first 200 picks (R1: 220) after a random start of size n, made in batches of 10 "
             f"as in a trajectory (selection only, nothing scored), mean over {len(SEEDS)} selection seeds; in "
             "brackets: one-shot batch of 200 (descriptive; the per-batch cluster cap spreads picks over clusters and "
             "dev1 cluster 5 is 34/40 off-array). Base = off-array share of the candidates. Acceptance |share − base| "
             f"≤ {TOL:.2f} (DESIGN §1, D5). M exempt (spec: off-array never picked after its round 0 = R0 batch). "
             "Generated by scripts/32_offarray_share_check.py.", "",
             "| strategy | " + " | ".join(f"n={n}" for n in NS) + " |", "|---|" + "---|" * len(NS)]
    for name in NAMES:
        cells = []
        for n in NS:
            r = next(x for x in rows if x["strategy"] == name and x["n"] == n)
            cells.append(f"{r['share']:.3f} [{r['oneshot200']:.3f}]"
                         + (" (exempt)" if r["exempt"] else ("" if r["ok"] else " **FAIL**")))
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines.append("| base (candidates) | " + " | ".join(
        f"{next(x for x in rows if x['n'] == n)['base']:.3f}" for n in NS) + " |")
    (d / "offarray_share.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
